import re,sys
defs={}
for l in open('u-boot/arch/arm/include/asm/arch-omap3/mux.h'):
    m=re.match(r'#define\s+CONTROL_PADCONF_(\w+)\s+(0x[0-9A-Fa-f]+)',l)
    if m: defs[int(m.group(2),16)]=m.group(1)
rows=[]
for l in open(sys.argv[1]):  # padconf dump: one "0xADDR=0xVALUE" per line
    a,v=l.strip().split('='); rows.append((int(a,16),int(v,16)))
out=[];skipped=[]
for a,v in rows:
    off=a-0x48002000
    names=[defs.get(off),defs.get(off+2)]
    if not any(names):
        skipped.append((hex(a),hex(v))); continue
    out.append((a,v,names))
print('// generated by gen-mux.py from the 2026-10-09 .188 padconf dump (see BUILD.md)')
print('static const struct rw20_pad { u32 addr; u32 val; } rw20_padconf[] = {')
for a,v,n in out:
    print('\t{ 0x%08x, 0x%08x }, /* %s */'%(a,v,'/'.join(x or '-' for x in n)))
print('};')
sys.stderr.write('words %d skipped %s\n'%(len(out),skipped))
