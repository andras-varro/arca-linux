# Descender glyphs replacing the old squashed g j p q y.  Rows 0..8, 5 columns,
# x-height rows 2-6 like the old lowercase, tails in rows 7-8.
DESCENDERS = {
    'g': ['.....', '.....', '.##.#', '#..##', '#...#', '#...#', '.####', '....#', '.###.'],
    'j': ['...#.', '.....', '...#.', '...#.', '...#.', '...#.', '...#.', '...#.', '.##..'],
    'p': ['.....', '.....', '#.##.', '##..#', '#...#', '#...#', '####.', '#....', '#....'],
    'q': ['.....', '.....', '.##.#', '#..##', '#...#', '#...#', '.####', '....#', '....#'],
    'y': ['.....', '.....', '#...#', '#...#', '#...#', '.####', '....#', '#...#', '.###.'],
}
FALLBACK = ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####', '.....', '.....']
PUNCT = [0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E, 0x2022, 0x2026, 0x20AC]


def parse_bdf(path):
    g, cur, inb = {}, None, False
    for ln in open(path, encoding='latin-1'):
        t = ln.split()
        if not t:
            continue
        if t[0] == 'STARTCHAR':
            cur, inb = {'rows': []}, False
        elif t[0] == 'ENCODING':
            cur['enc'] = int(t[1])
        elif t[0] == 'BBX':
            cur['bbx'] = tuple(int(x) for x in t[1:5])
        elif t[0] == 'BITMAP':
            inb = True
        elif t[0] == 'ENDCHAR':
            inb = False
            if cur['enc'] >= 0:
                g[cur['enc']] = cur
        elif inb:
            cur['rows'].append(int(t[0], 16))
    return g


def bdf_cols(c):
    w, h, xo, yo = c['bbx']
    cols = [0] * 6
    for i, v in enumerate(c['rows']):
        row = 7 - 1 - (yo + h - 1 - i)          # ascent 7: top glyph row 6 -> cell row 0
        assert 0 <= row <= 8
        for x in range(w):
            if (v >> (7 - x)) & 1:
                assert 0 <= x + xo <= 5
                cols[x + xo] |= 1 << row
    return cols


def strs_cols(rows):
    cols = [0] * 6
    for r, s in enumerate(rows):
        assert len(s) == 5
        for x, ch in enumerate(s):
            if ch == '#':
                cols[x] |= 1 << r
    return cols


def fmt(cols, label):
    return '    {%s},  /* %s */' % (', '.join('0x%03X' % v for v in cols), label)


def main():
    bdf, out = sys.argv[1], sys.argv[2]
    g = parse_bdf(bdf)
    L = []
    L.append('/* GENERATED by native_apps/gen_font.py from the misc-fixed 6x9 BDF and the old')
    L.append(' * 5x7 ASCII table.  Do not edit; rerun the generator.  Column c of a glyph is a')
    L.append(' * uint16: bit r = ink at row r (row 0 = top of the 9-row cell, rows 7-8 = descenders). */')
    L.append('')
    L.append('static const uint16_t font_ascii[95][FONT_COLS] = {')
    for i, old in enumerate(OLD_ASCII):
        ch = chr(32 + i)
        cols = list(old) + [0]
        assert all(v < 0x80 for v in old)
        if ch in DESCENDERS:
            cols = strs_cols(DESCENDERS[ch])
        L.append(fmt(cols, ch if ch not in '\\' else 'backslash'))
    L.append('};')
    L.append('')
    L.append('static const uint16_t font_l1[96][FONT_COLS] = {  /* U+00A0..U+00FF */')
    for cp in range(0xA0, 0x100):
        L.append(fmt(bdf_cols(g[cp]), 'U+%04X' % cp))
    L.append('};')
    L.append('')
    L.append('static const uint16_t font_ea[128][FONT_COLS] = {  /* U+0100..U+017F */')
    for cp in range(0x100, 0x180):
        L.append(fmt(bdf_cols(g[cp]), 'U+%04X' % cp))
    L.append('};')
    L.append('')
    L.append('static const struct { uint32_t cp; uint16_t g[FONT_COLS]; } font_punct[] = {  /* sorted */')
    for cp in sorted(PUNCT):
        c = bdf_cols(g[cp])
        L.append('    {0x%04X, {%s}},' % (cp, ', '.join('0x%03X' % v for v in c)))
    L.append('};')
    L.append('')
    ext = [cp for cp in range(0x370, 0x500) if cp in g]
    L.append('static const struct { uint32_t cp; uint16_t g[FONT_COLS]; } font_ext[] = {  /* sorted: Greek U+0370..03FF, Cyrillic U+0400..04FF, those the BDF has */')
    for cp in ext:
        L.append('    {0x%04X, {%s}},' % (cp, ', '.join('0x%03X' % v for v in bdf_cols(g[cp]))))
    L.append('};')
    L.append('')
    L.append('static const uint16_t font_fallback[FONT_COLS] = {%s};' %
             ', '.join('0x%03X' % v for v in strs_cols(FALLBACK)))
    with open(out, 'w', newline='\n') as f:
        f.write('\n'.join(L) + '\n')


main()
